// Regenerates src/data/mapDots.ts (the dot-matrix land on the Global map).
// Run with: npm run map
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const topo = require('world-atlas/land-50m.json');
const land = feature(topo, topo.objects.land);

const polys = [];
for (const f of land.features ?? [land]) {
  const g = f.geometry;
  for (const p of g.type === 'Polygon' ? [g.coordinates] : g.coordinates) {
    let [minx, miny, maxx, maxy] = [Infinity, Infinity, -Infinity, -Infinity];
    for (const [x, y] of p[0]) { minx = Math.min(minx, x); maxx = Math.max(maxx, x); miny = Math.min(miny, y); maxy = Math.max(maxy, y); }
    polys.push({ rings: p, bb: [minx, miny, maxx, maxy] });
  }
}
const inRing = (x, y, r) => {
  let c = false;
  for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
    const [xi, yi] = r[i], [xj, yj] = r[j];
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
};
const isLand = (x, y) => polys.some(({ rings, bb }) =>
  x >= bb[0] && x <= bb[2] && y >= bb[1] && y <= bb[3] && inRing(x, y, rings[0]) && !rings.slice(1).some((h) => inRing(x, y, h)));

// Must match project() in src/lib/format.ts
const LON0 = -20, LON1 = 60, LAT0 = 0, LAT1 = 62, K = Math.cos((35 * Math.PI) / 180), STEP = 0.8;
const W = (LON1 - LON0) * K, H = LAT1 - LAT0;
let d = '';
for (let y = STEP / 2; y < H; y += STEP)
  for (let x = STEP / 2; x < W; x += STEP)
    if (isLand(LON0 + x / K, LAT1 - y)) d += `M${x.toFixed(1)} ${y.toFixed(1)}h0`;

writeFileSync(new URL('../src/data/mapDots.ts', import.meta.url),
  `// Generated by scripts/generate-map.mjs. Dot-matrix land for 20°W–60°E, 0°–62°N.\nexport const DOTS = "${d}";\n`);
console.log(`Wrote ${d.length} characters of map data.`);
